#!/usr/bin/env bash
# Write THIRD-PARTY-LICENSES.md: the license notices of every crate compiled
# into the released binaries (`concurv`, `concurvd`) for the release targets.
# The texts come from the crates' own license files in the local cargo
# registry (run `cargo fetch` first); identical texts are printed once.
#
#   scripts/third-party-licenses.sh [OUT]   # default: THIRD-PARTY-LICENSES.md
set -euo pipefail
repo=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$repo/THIRD-PARTY-LICENSES.md}
cargo_home=${CARGO_HOME:-$HOME/.cargo}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

cd "$repo"
for t in x86_64-pc-windows-msvc x86_64-unknown-linux-musl; do
    cargo tree --locked -p concurv-cli -e normal --target "$t" --prefix none \
        --format '{p}|{l}' |
        sed 's/ (\*)//; s/ (proc-macro)//' |
        grep -v '^concurv' || true
done | sort -u >"$work/deps"

# name vX.Y.Z|license -> registry directory
crate_dir() {
    local name=$1 version=$2 d
    for d in "$cargo_home"/registry/src/*/"$name-$version"; do
        [ -d "$d" ] && { echo "$d"; return 0; }
    done
    return 1
}

: >"$work/index"
missing=()
while IFS='|' read -r pv lic; do
    name=${pv% v*}
    version=${pv##* v}
    dir=$(crate_dir "$name" "$version") || { missing+=("$name $version"); continue; }
    found=0
    while IFS= read -r -d '' f; do
        h=$(sha256sum "$f" | cut -c1-16)
        [ -f "$work/text-$h" ] || cp "$f" "$work/text-$h"
        printf '%s\t%s\t%s\t%s\n' "$h" "$name $version" "$lic" "$(basename "$f")" >>"$work/index"
        found=1
    done < <(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' \
        -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'UNLICENSE*' \) -print0 | sort -z)
    [ "$found" = 1 ] || missing+=("$name $version ($lic): no license file in the package")
done <"$work/deps"

{
    echo "# Third-party licenses"
    echo
    echo "The \`concurv\` and \`concurvd\` binaries contain the following crates."
    echo "concurv itself is licensed under MIT OR Apache-2.0 (\`LICENSE-MIT\`,"
    echo "\`LICENSE-APACHE\`). Generated by \`scripts/third-party-licenses.sh\` from"
    echo "\`Cargo.lock\` for the release targets (Windows x86_64, Linux x86_64 musl)."
    echo
    echo "| Crate | License |"
    echo "|---|---|"
    cut -d'|' -f1,2 "$work/deps" | sed 's/^\(.*\)|\(.*\)$/| \1 | \2 |/'
    echo
    if [ ${#missing[@]} -gt 0 ]; then
        echo "Crates without a license file in their package (their license is the"
        echo "SPDX expression above; see the crate's repository for its notice):"
        echo
        for m in "${missing[@]}"; do echo "- $m"; done
        echo
    fi
    echo "## License texts"
    for h in $(cut -f1 "$work/index" | sort -u); do
        echo
        echo "### Used by"
        echo
        awk -F'\t' -v h="$h" '$1 == h { printf "- %s (%s, file `%s`)\n", $2, $3, $4 }' "$work/index"
        echo
        echo '```text'
        tr -d '\r' <"$work/text-$h"
        echo '```'
    done
} >"$out"
echo "third-party-licenses: $(wc -l <"$work/deps") crates, $(cut -f1 "$work/index" | sort -u | wc -l) distinct texts, ${#missing[@]} without a file -> $out"
